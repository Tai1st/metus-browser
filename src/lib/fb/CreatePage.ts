export function generateRandomName(): string {
  const first = FIRST_NAMES[Math.floor(Math.random() * FIRST_NAMES.length)];
  const last = LAST_NAMES[Math.floor(Math.random() * LAST_NAMES.length)];
  return `${first} ${last}`;
}

export function generateNameList(count: number): string {
  return Array.from({ length: count }, generateRandomName).join('\n');
}

function randomEmojis(count: number): string {
  return Array.from({ length: count }, () => EMOJIS[Math.floor(Math.random() * EMOJIS.length)]).join(' ');
}

export function addRandomEmojisToBio(bio: string, count = 3): string {
  return `${bio} ${randomEmojis(count)}`;
}

export interface PageCreationResult {
  success: boolean;
  pageId?: string;
  pageName: string;
  pageUrl?: string;
  error?: string;
}

async function createFacebookPage(dtsg: string, fbId: string, name: string, bio: string, clientMutationId: string): Promise<PageCreationResult> {
  const variables = {
    input: {
      bio: bio.substring(0, 255),
      categories: ['2201'],
      creation_source: 'comet',
      name: name.trim(),
      page_referrer: 'launch_point',
      actor_id: fbId,
      client_mutation_id: clientMutationId,
    },
  };

  const form = new FormData();
  form.append('fb_dtsg', dtsg);
  form.append('av', fbId);
  form.append('server_timestamps', 'true');
  form.append('doc_id', '5903223909690825');
  form.append('variables', JSON.stringify(variables));
  form.append('jazoest', '25383');
  form.append('__a', '1');
  form.append('__user', fbId);

  try {
    const { data: parsed } = await instance.post<any>(GRAPHQL, form);
    if (parsed?.errors?.length) {
      const err = parsed.errors[0];
      return { success: false, pageName: name, error: err?.message ?? 'Lỗi không xác định từ Facebook' };
    }
    const pageData = parsed?.data?.additional_profile_plus_create;
    if (!pageData) return { success: false, pageName: name, error: 'Phản hồi không đúng định dạng mong đợi' };
    if (pageData.name_error) return { success: false, pageName: name, error: pageData.name_error };
    if (pageData.error_message) return { success: false, pageName: name, error: pageData.error_message };
    const pageId: string | undefined = pageData.page?.id || pageData.additional_profile?.id;
    if (!pageId) return { success: false, pageName: name, error: 'Phản hồi không đúng định dạng mong đợi' };
    return { success: true, pageId, pageName: name, pageUrl: `https://www.facebook.com/${pageId}` };
  } catch (e) {
    return { success: false, pageName: name, error: e instanceof Error ? e.message : String(e) };
  }
}

export interface BulkCreateOptions {
  randomEmoji?: boolean;
  emojiCount?: number;
  delaySeconds?: number;
  onProgress?: (result: PageCreationResult, current: number, total: number) => void;
  shouldStop?: () => boolean;
}

/** Tạo nhiều Page lần lượt, giãn cách giữa mỗi lần (kiểm tra dừng mỗi giây để Dừng phản hồi nhanh). */
export async function createMultiplePages(dtsg: string, fbId: string, pageNames: string[], bioTemplate: string, options: BulkCreateOptions = {}): Promise<PageCreationResult[]> {
  const { randomEmoji = false, emojiCount = 3, delaySeconds = 60, onProgress, shouldStop } = options;
  const results: PageCreationResult[] = [];
  for (let i = 0; i < pageNames.length; i++) {
    if (shouldStop?.()) break;
    const bio = randomEmoji ? addRandomEmojisToBio(bioTemplate, emojiCount) : bioTemplate;
    const result = await createFacebookPage(dtsg, fbId, pageNames[i], bio, String(i + 1));
    results.push(result);
    onProgress?.(result, i + 1, pageNames.length);
    if (i < pageNames.length - 1 && delaySeconds > 0) {
      for (let waited = 0; waited < delaySeconds; waited++) {
        if (shouldStop?.()) break;
        await new Promise((r) => setTimeout(r, 1000));
      }
    }
  }
  return results;
}
